/**
 * A type that represents various binary object types in JavaScript.
 *
 * @group Encoding
 * @category Binary
 */
export type BinaryObject =
  | ArrayBuffer
  | DataView
  | Int8Array
  | Uint8Array
  | Uint8ClampedArray
  | Int16Array
  | Uint16Array
  | Int32Array
  | Uint32Array
  | Float32Array
  | Float64Array;
